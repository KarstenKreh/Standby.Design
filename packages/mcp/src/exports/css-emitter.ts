// MCP-local CSS emitter. Minimal, shadcn-compatible output for LLM consumption.
// Deliberately simpler than color-react's generateSemantic: no accent scopes,
// no pinned/invert logic. LLMs almost never need those for v0. If they become
// needed, prefer extracting a unified emitter to @core rather than adding
// knobs here.

import type { PaletteEntry } from '@core/palette';
import type { PaletteSet } from '@core/orchestrate';
import type { ComputedLevel } from '@core/scale';
import type { SpacingToken } from '@core/spacing';

interface ColorEmitInput {
  paletteSet: PaletteSet;
  chromaScale: number;
  themeName: string;
}

interface TypeEmitInput {
  levels: ComputedLevel[];
  spacingTokens: SpacingToken[];
  headingFont: string;
  bodyFont: string;
  monoFont: string;
  scaleLabel: string;
}

function formatSection(palette: PaletteEntry[], prefix: string, valueMode: 'css' | 'hex'): string {
  const zones = [
    { label: 'Light Surfaces', match: (p: PaletteEntry) => p.step <= 100 },
    { label: 'Core', match: (p: PaletteEntry) => p.step >= 200 && p.step <= 800 },
    { label: 'Dark Surfaces', match: (p: PaletteEntry) => p.step >= 825 && p.step <= 875 },
    { label: 'High Contrast', match: (p: PaletteEntry) => p.step >= 900 },
  ];
  let out = '';
  zones.forEach((zone, i) => {
    if (i > 0) out += '\n';
    out += `  /* ${zone.label} */\n`;
    palette.filter(zone.match).forEach((entry) => {
      const value = valueMode === 'css' ? entry.css : entry.hex;
      out += `  --color-${prefix}-${entry.step}: ${value};\n`;
    });
  });
  return out;
}

export function emitColorCss(input: ColorEmitInput): string {
  const { paletteSet, chromaScale, themeName } = input;
  const pct = Math.round(chromaScale * 100);
  const header = themeName
    ? `/* ${themeName} — Color Tokens */`
    : `/* Color Tokens — generated by @standby-design/mcp */`;

  let css = `${header}\n:root {\n`;
  css += `\n  /* Brand */\n`;
  css += formatSection(paletteSet.brand, 'brand', 'css');
  css += `\n  /* Surface — ${pct}% chroma */\n`;
  css += formatSection(paletteSet.surface, 'surface', 'css');
  css += `\n  /* Error */\n`;
  css += formatSection(paletteSet.error, 'error', 'css');
  css += `\n  /* Error Surface — ${pct}% chroma */\n`;
  css += formatSection(paletteSet.errorSurface, 'error-surface', 'css');
  css += `\n  /* Neutral */\n`;
  css += formatSection(paletteSet.neutral, 'neutral', 'css');
  css += `}\n\n`;

  // Semantic tokens — shadcn/ui compatible.
  css += `/* Semantic Tokens — shadcn/ui compatible */\n`;
  css += `:root {\n`;
  css += `  --background: var(--color-surface-50);\n`;
  css += `  --foreground: var(--color-surface-975);\n`;
  css += `  --card: var(--color-surface-25);\n`;
  css += `  --card-foreground: var(--color-surface-975);\n`;
  css += `  --popover: var(--color-surface-25);\n`;
  css += `  --popover-foreground: var(--color-surface-975);\n`;
  css += `  --primary: var(--color-brand-600);\n`;
  css += `  --primary-foreground: var(--color-brand-50);\n`;
  css += `  --secondary: var(--color-brand-200);\n`;
  css += `  --secondary-foreground: var(--color-brand-900);\n`;
  css += `  --muted: var(--color-surface-75);\n`;
  css += `  --muted-foreground: var(--color-surface-700);\n`;
  css += `  --accent: var(--color-brand-100);\n`;
  css += `  --accent-foreground: var(--color-brand-900);\n`;
  css += `  --destructive: var(--color-error-600);\n`;
  css += `  --destructive-foreground: var(--color-error-surface-50);\n`;
  css += `  --border: var(--color-surface-300);\n`;
  css += `  --border-muted: var(--color-surface-200);\n`;
  css += `  --input: var(--color-surface-300);\n`;
  css += `  --ring: var(--color-surface-400);\n`;
  css += `}\n\n`;

  css += `.dark {\n`;
  css += `  --background: var(--color-surface-875);\n`;
  css += `  --foreground: var(--color-surface-25);\n`;
  css += `  --card: var(--color-surface-825);\n`;
  css += `  --card-foreground: var(--color-surface-25);\n`;
  css += `  --popover: var(--color-surface-800);\n`;
  css += `  --popover-foreground: var(--color-surface-25);\n`;
  css += `  --primary: var(--color-brand-400);\n`;
  css += `  --primary-foreground: var(--color-brand-975);\n`;
  css += `  --secondary: var(--color-brand-800);\n`;
  css += `  --secondary-foreground: var(--color-brand-100);\n`;
  css += `  --muted: var(--color-surface-850);\n`;
  css += `  --muted-foreground: var(--color-surface-300);\n`;
  css += `  --accent: var(--color-brand-800);\n`;
  css += `  --accent-foreground: var(--color-brand-100);\n`;
  css += `  --destructive: var(--color-error-400);\n`;
  css += `  --destructive-foreground: var(--color-error-surface-975);\n`;
  css += `  --border: var(--color-surface-600);\n`;
  css += `  --border-muted: var(--color-surface-700);\n`;
  css += `  --input: var(--color-surface-700);\n`;
  css += `  --ring: var(--color-surface-500);\n`;
  css += `}\n`;

  return css;
}

export function emitTypeCss(input: TypeEmitInput): string {
  const { levels, spacingTokens, headingFont, bodyFont, monoFont, scaleLabel } = input;
  let css = `/* Type Scale — ${scaleLabel} */\n:root {\n`;
  css += `  /* Font Families */\n`;
  css += `  --font-heading: ${headingFont}, sans-serif;\n`;
  css += `  --font-body: ${bodyFont}, sans-serif;\n`;
  css += `  --font-mono: ${monoFont}, monospace;\n`;

  css += `\n  /* Type Scale */\n`;
  for (const l of levels) css += `  --text-${l.level}: ${l.clampValue};\n`;

  css += `\n  /* Line Heights */\n`;
  for (const l of levels) css += `  --leading-${l.level}: ${l.lineHeight};\n`;

  css += `\n  /* Letter Spacing */\n`;
  for (const l of levels) css += `  --tracking-${l.level}: ${l.letterSpacing}em;\n`;

  if (spacingTokens.length > 0) {
    css += `\n  /* Spacing Scale */\n`;
    for (const t of spacingTokens) css += `  --space-${t.name}: ${t.rem}rem;\n`;
  }

  css += `}\n`;
  return css;
}

export function emitTypeTailwind(input: TypeEmitInput): string {
  const { levels, spacingTokens, headingFont, bodyFont, monoFont, scaleLabel } = input;
  let css = `/* Type Scale — ${scaleLabel} */\n@theme {\n`;
  css += `  --font-heading: ${headingFont}, sans-serif;\n`;
  css += `  --font-body: ${bodyFont}, sans-serif;\n`;
  css += `  --font-mono: ${monoFont}, monospace;\n\n`;

  for (const l of levels) css += `  --text-${l.level}: ${l.clampValue};\n`;
  css += `\n`;
  for (const l of levels) css += `  --leading-${l.level}: ${l.lineHeight};\n`;
  css += `\n`;
  for (const l of levels) css += `  --tracking-${l.level}: ${l.letterSpacing}em;\n`;

  if (spacingTokens.length > 0) {
    css += `\n`;
    for (const t of spacingTokens) css += `  --space-${t.name}: ${t.rem}rem;\n`;
  }

  css += `}\n`;
  return css;
}
